package com.young.metaboliccoach.core.model

enum class CoachTheme {
    SYSTEM,
    DARK,
    HIGH_CONTRAST,
}

enum class GlucoseProviderMode {
    NIGHTSCOUT,
    HEALTH_CONNECT,
    XDRIP_BROADCAST,
    CARESENS_PARTNER,
}

data class CoachSettings(
    val glucoseProviderMode: GlucoseProviderMode,
    val healthConnectGlucoseOriginPackage: String?,
    val glucoseUnit: GlucoseUnit,
    val lowGlucoseThresholdMgDl: Int,
    val targetLowerMgDl: Int,
    val targetUpperMgDl: Int,
    val rapidRiseThresholdMgDlPerMinute: Double,
    val exercisePauseFallRateMgDlPerMinute: Double,
    val staleReadingMinutes: Int,
    val walkingDurationMinutes: Int,
    val stairTargetFloors: Int,
    val dailyStepGoal: Int,
    val dailyFloorGoal: Int,
    val prolongedInactivityMinutes: Int,
    val postMealDelayMinutes: Int,
    val postMealWindowMinutes: Int,
    val reminderCooldownMinutes: Int,
    val snoozeMinutes: Int,
    val maximumNotificationsPerDay: Int,
    val quietHoursStartMinuteOfDay: Int,
    val quietHoursEndMinuteOfDay: Int,
    val workingHoursStartMinuteOfDay: Int,
    val workingHoursEndMinuteOfDay: Int,
    val minimumObservationSamples: Int,
    val minimumTimingBucketSamples: Int,
    val minimumComparableTimingBuckets: Int,
    val interventionTimingBucketMinutes: Int,
    val postMealTimingBucketMinutes: Int,
    val followUpDelayBucketMinutes: Int,
    val baselineGlucoseBandMgDl: Int,
    val interventionFollowUpMinutes: Int,
    val quickActionExpiryMinutes: Int,
    val walkingRemindersEnabled: Boolean,
    val stairRemindersEnabled: Boolean,
    val postMealRemindersEnabled: Boolean,
    val notificationsEnabled: Boolean,
    val theme: CoachTheme,
    val fontScale: Float,
)

