        dailyStepGoal = 8_000,
        dailyFloorGoal = 10,
        prolongedInactivityMinutes = 60,
        postMealDelayMinutes = 30,
        postMealWindowMinutes = 45,
        reminderCooldownMinutes = 60,
        snoozeMinutes = 15,
        maximumNotificationsPerDay = 6,
        quietHoursStartMinuteOfDay = 22 * 60,
        quietHoursEndMinuteOfDay = 7 * 60,
        workingHoursStartMinuteOfDay = 8 * 60,
        workingHoursEndMinuteOfDay = 18 * 60,
        minimumObservationSamples = 3,
        minimumTimingBucketSamples = 8,
